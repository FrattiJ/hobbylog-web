// Regenerates src/lib/fitness/catalog.data.ts from free-exercise-db.
//
//   node scripts/build-exercise-catalog.mjs
//
// Source: https://github.com/yuhonas/free-exercise-db (public domain, ~873 exercises).
// We bundle the catalog instead of calling an exercise API at runtime: it never
// changes, needs no key, and keeps the picker instant/offline. Only the fields the
// picker actually shows are kept, packed as tuples to hold the chunk down.
import { writeFileSync } from 'node:fs'

const SRC = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json'
const OUT = new URL('../src/lib/fitness/catalog.data.ts', import.meta.url)

const raw = await fetch(SRC).then((r) => r.json())

// Stable dictionaries so the tuples can store small integer indexes.
const equipment = [...new Set(raw.map((e) => e.equipment || 'other'))].sort()
const categories = [...new Set(raw.map((e) => e.category))].sort()
const muscles = [...new Set(raw.flatMap((e) => e.primaryMuscles))].sort()

const rows = raw
  .map((e) => [
    e.id,
    e.name,
    equipment.indexOf(e.equipment || 'other'),
    categories.indexOf(e.category),
    e.primaryMuscles.map((m) => muscles.indexOf(m)),
  ])
  .sort((a, b) => a[1].localeCompare(b[1]))

const ts = `// GENERATED by scripts/build-exercise-catalog.mjs — do not edit by hand.
// Source: free-exercise-db (public domain). ${rows.length} exercises.
// Row shape: [id, name, equipmentIndex, categoryIndex, primaryMuscleIndexes]
export type CatalogRow = [string, string, number, number, number[]]

export const EQUIPMENT: readonly string[] = ${JSON.stringify(equipment)}
export const CATEGORIES: readonly string[] = ${JSON.stringify(categories)}
export const MUSCLES: readonly string[] = ${JSON.stringify(muscles)}

export const ROWS: readonly CatalogRow[] = ${JSON.stringify(rows)}
`

writeFileSync(OUT, ts)
console.log(`wrote ${rows.length} exercises, ${(ts.length / 1024).toFixed(0)} KB`)
